import test from "node:test";
import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {spawnSync} from "node:child_process";

test("MO-REL08 production additive schema runner keeps actual Control intact and proves restorable backup",async()=>{
 const src=await readFile("scripts/deploy/devserver01-prod-control-additive.sh","utf8");
 const ci=await readFile(".github/workflows/syndes-ci.yml","utf8");
 assert.match(src,/syndes-postgres/);
 assert.match(src,/label=com\.docker\.compose\.service=postgres/);
 assert.match(src,/postgres:17-bookworm/);
 assert.match(src,/SYNDES_PROD_CONTROL_RELEASE/);
 assert.match(src,/SYNDES_RELEASE_SHA/);
 assert.match(src,/CI_APPROVED_MO_REL08_ADDITIVE/);
 assert.match(src,/artifact_checksum/);
 assert.match(src,/pg_dump -Fc/);
 assert.match(src,/pg_restore --no-owner --no-privileges/);
 assert.match(src,/--network none/);
 assert.match(src,/--single-transaction/);
 assert.match(src,/MO_REL08_PROD_CONTROL_REAL_BACKUP_RESTORE_AND_MIGRATION_REPLAY_PASS/);
 assert.match(src,/MO_REL08_PROD_CONTROL_ADDITIVE_CATALOG_LIFECYCLE_APPLIED_NO_TENANT_OR_AUTH_SWITCH/);
 assert.match(src,/tenant_module_entitlements WHERE state='granted'/);
 assert.match(src,/syndes-prod-control-releases/);
 assert.match(src,/partial_module_schema/);
 assert.doesNotMatch(src,/activate_multiple_organizations\.sql|002_legacy_single_context_gate|SYNDES_MULTI_ORG_ENABLED|DROP DATABASE|DROP TABLE|docker compose (?:up|down)|docker restart/);
 const syntax=spawnSync("bash",["-n","scripts/deploy/devserver01-prod-control-additive.sh"],{encoding:"utf8"});
 assert.equal(syntax.status,0,syntax.stderr);
 const pos=ci.indexOf("  devserver01-prod-control-additive:");
 assert.ok(pos>0,"mainline must contain a narrowly approved operational job");
 const rest=ci.slice(pos+1);
 const next=rest.search(/\n  [a-z][a-z0-9-]+:\n/);
 const job=next<0?ci.slice(pos):ci.slice(pos,pos+1+next);
 assert.match(job,/MO-REL08-PROD-CONTROL-ADDITIVE-APPROVED/);
 assert.match(job,/needs: \[gate\]/);
 assert.match(job,/github\.event_name == 'push'/);
 assert.match(job,/github\.ref == 'refs\/heads\/main'/);
 assert.match(job,/git ls-remote origin refs\/heads\/main/);
 assert.match(job,/tailscale\/github-action@v4/);
 assert.match(job,/devserver01-prod-control-additive\.sh/);
 assert.match(job,/PRODUCTION_GATE=BLOCKED/);
 assert.doesNotMatch(job,/activate_multiple_organizations\.sql|SYNDES_MULTI_ORG_ENABLED=true|SQL002_CUTOVER_APPROVED/);
});
